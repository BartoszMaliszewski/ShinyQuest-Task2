const ZA_DEX = Object.freeze(ZA_POKEDEX_ROWS.split("\n").map((row, index) => {
  const match = row.trim().match(/^(\d+)\s+(.+)$/);
  if (!match) throw Error("Bad Pokédex row: " + row);
  return Object.freeze({number: index + 1, pokemonId: Number(match[1]), name: match[2], locked: ZA_LOCKED_IDS.has(Number(match[1]))});
}));
const ZA_DEX_BY_ID = new Map(ZA_DEX.map((item) => [item.pokemonId, item]));